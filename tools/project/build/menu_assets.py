"""Generate the bridge's embedded antialiased glyphs (requires Pillow)."""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

# Printable ASCII plus the Chinese UI subset. Additional labels can extend this set.
CHINESE = '选择启动方式一个入口开始下一步继续系统连接电脑进行传输与调试进入固件命令打开原有菜单等待选好后按电源键确认秒取消自动已返回可重新音量小米'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True, help='OFL NotoSansCJK-Regular.ttc')
    parser.add_argument('--font-index', type=int, default=2, help='Simplified Chinese face in TTC')
    parser.add_argument('--output', type=Path, default=Path('boot/bridge/menu/assets/menu_font.h'))
    args = parser.parse_args()
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(str(args.font), 256, index=args.font_index)
    records, data = [], bytearray()
    maximum = 0
    characters = sorted(set(chr(n) for n in range(32, 127)) | set(CHINESE + '，。·'))
    for character in characters:
        bbox = font.getbbox(character, anchor='ls')
        left, top = bbox[0] // 4 - 1, bbox[1] // 4 - 1
        width = (bbox[2] + 3) // 4 - left + 1
        height = (bbox[3] + 3) // 4 - top + 1
        image = Image.new('L', (width * 4, height * 4))
        ImageDraw.Draw(image).text((-left*4, -top*4), character, font=font, fill=255, anchor='ls')
        raw = image.resize((width, height), Image.Resampling.LANCZOS).tobytes()
        maximum = max(maximum, len(raw))
        offset, cursor = len(data), 0
        while cursor < len(raw):
            count = 1
            while cursor + count < len(raw) and count < 255 and raw[cursor + count] == raw[cursor]:
                count += 1
            data.extend((count, raw[cursor]))
            cursor += count
        records.append((ord(character), offset, len(data)-offset, width, height,
                        left, top, round(font.getlength(character)/4)))
    lines = [
        '// SPDX-License-Identifier: OFL-1.1',
        '// Generated by tools/project/build/menu_assets.py; do not edit.',
        '// Copyright 2014-2021 Adobe (http://www.adobe.com/). Noto is a trademark of Google Inc.',
        '// Source: https://github.com/notofonts/noto-cjk ; license: OFL-NotoSansCJK.txt',
        '// Font SHA256: ' + hashlib.sha256(args.font.read_bytes()).hexdigest(),
        '#pragma once',
        'struct menu_glyph { unsigned code, offset, bytes, width, height; int left, top, advance; };',
        f'#define MENU_GLYPH_SCRATCH {maximum}u',
        'static const struct menu_glyph menu_glyphs[] = {',
        *['    {' + ','.join(map(str, record)) + '},' for record in records],
        '};',
        'static const unsigned char menu_glyph_data[] = {',
    ]
    lines += ['    '+','.join(str(v) for v in data[i:i+32])+',' for i in range(0, len(data), 32)]
    lines += ['};', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines))
    print(f'{len(records)} glyphs, {len(data)} bytes RLE, {maximum} bytes scratch')


if __name__ == '__main__':
    main()
