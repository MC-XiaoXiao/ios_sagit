#!/usr/bin/env python3
"""Generate sagit CPRh/OSM data from the pinned Xiaomi v2 DTS.

This deliberately parses only the numeric properties used below. It is not a
general DTS parser; source hashes and expected property shapes are checked.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs/power/reference"
OUTPUT = ROOT / "drivers/clock/QcomOSM/CPRhSagitV2Tables.h"


def checked(name):
    manifest = json.loads((ROOT / "docs/power/osm-reference-sources.json").read_text())
    entry = next(x for x in manifest["sources"] if x.get("path", "").endswith("/" + name))
    data = (REFERENCE / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise ValueError(f"reference hash mismatch: {name}")
    text = data.decode()
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def body(text, label, overlay=False):
    pattern = (r"&" + label + r"\s*\{") if overlay else (label + r":\s*[^\s{]+\s*\{")
    match = re.search(pattern, text)
    if not match:
        raise ValueError(f"missing node {label}")
    start = match.end()
    depth, pos = 1, start
    while depth:
        if text[pos] == "{":
            depth += 1
        elif text[pos] == "}":
            depth -= 1
        pos += 1
    return text[start : pos - 1]


def properties(text):
    result = {}
    for match in re.finditer(r"([\w,#-]+)\s*=\s*((?:<[^>]*>\s*,?\s*)+);", text):
        raw = match[2].replace("<", " ").replace(">", " ").replace(",", " ")
        raw = raw.replace("(", " ").replace(")", " ")
        tokens = raw.split()
        if not all(re.fullmatch(r"-?(?:0x[0-9a-fA-F]+|\d+)", x) for x in tokens):
            continue
        result[match[1]] = [int(x, 0) for x in tokens]
    return result


FIELDS = {
    "counts": "qcom,cpr-corners",
    "fmax": "qcom,cpr-corner-fmax-map",
    "frequency": "qcom,corner-frequencies",
    "ceiling": "qcom,cpr-voltage-ceiling",
    "floor": "qcom,cpr-voltage-floor",
    "range": "qcom,cpr-floor-to-ceiling-max-range",
    "roScale": "qcom,cpr-ro-scaling-factor",
    "openFuse": "qcom,cpr-open-loop-voltage-fuse-adjustment",
    "closedFuse": "qcom,cpr-closed-loop-voltage-fuse-adjustment",
    "openAdjust": "qcom,cpr-open-loop-voltage-adjustment",
    "closedAdjust": "qcom,cpr-closed-loop-voltage-adjustment",
}


def generate():
    manifest = json.loads((ROOT / "docs/power/osm-reference-sources.json").read_text())
    for entry in manifest["sources"]:
        if "path" not in entry:
            continue  # Recorded unsuccessful lookup, not a source dependency.
        data = (ROOT / entry["path"]).read_bytes()
        if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError(f"reference hash/length mismatch: {entry['path']}")
    base = checked("xiaomi-msm8998-regulator.dtsi")
    v2 = checked("xiaomi-msm8998-v2.dtsi")
    v21 = checked("xiaomi-msm8998-v2.1.dtsi")
    sagit = checked("xiaomi-sagit-msm8998-mtp.dtsi")
    for name in ("xiaomi-sagit-msm8998-v2-mtp.dts", "xiaomi-sagit-msm8998-v2.1-mtp.dts"):
        if "qcom,board-id = <30 0>" not in checked(name):
            raise ValueError("sagit board identity changed")
    if re.search(r"&(?:apc[01]|clock_cpu)", sagit + v21):
        raise ValueError("unexpected board/revision CPR or OSM override")
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-only",
        "// Generated by scripts/generate-cprh-tables.py; do not edit.",
        "// Xiaomi sagit-n-oss commit 3fb35ef1f0fe1f714be3df39724cbc8eb217181e.",
        "#pragma once",
        "#include <stdint.h>",
        "namespace QcomCPRh { namespace Data {",
        "struct Array { const int64_t *values; unsigned count; };",
        "struct Cluster {",
        "    Array " + ", ".join(FIELDS) + ";",
        "};",
    ]
    # CPRhInitialization.h intentionally has a single, fixed hardware profile.
    # Fail generation if a source update changes any controller/thread policy.
    controller_values = {
        "qcom,cpr-sensor-time": 1000, "qcom,cpr-loop-time": 5000000,
        "qcom,cpr-idle-cycles": 15, "qcom,cpr-step-quot-init-min": 11,
        "qcom,cpr-step-quot-init-max": 12, "qcom,cpr-count-mode": 0,
        "qcom,cpr-count-repeat": 1, "qcom,cpr-down-error-step-limit": 1,
        "qcom,cpr-up-error-step-limit": 1, "qcom,cpr-corner-switch-delay-time": 1042,
        "qcom,cpr-voltage-settling-time": 1760, "qcom,apm-threshold-voltage": 800000,
        "qcom,apm-crossover-voltage": 880000, "qcom,apm-hysteresis-voltage": 0,
        "qcom,mem-acc-threshold-voltage": 852000, "qcom,mem-acc-crossover-voltage": 852000,
        "qcom,voltage-step": 4000, "qcom,voltage-base": 352000,
        "qcom,cpr-thread-id": 0, "qcom,cpr-consecutive-up": 0,
        "qcom,cpr-consecutive-down": 2, "qcom,cpr-up-threshold": 2,
        "qcom,cpr-down-threshold": 2,
    }
    for label in ("apc0_cpr", "apc1_cpr"):
        combined = body(base, label) + body(v2, label, True)
        props = properties(body(base, label))
        props.update(properties(body(v2, label, True)))
        for name, value in controller_values.items():
            if label == "apc1_cpr" and name == "qcom,cpr-step-quot-init-min":
                value = 9
            if label == "apc1_cpr" and name == "qcom,cpr-step-quot-init-max":
                value = 14
            if props[name] != [value]:
                raise ValueError(f"unsupported controller policy {label}: {name}")
        for flag in ("qcom,cpr-saw-use-unit-mV", "qcom,cpr-enable", "qcom,cpr-hw-closed-loop"):
            if flag not in combined:
                raise ValueError(f"required controller flag missing: {flag}")
        for flag in ("qcom,cpr-reset-step-quot-loop-en", "qcom,cpr-step-quot-fixed"):
            if flag in combined:
                raise ValueError(f"unsupported controller flag present: {flag}")
    for cluster, label in enumerate(("apc0_pwrcl_vreg", "apc1_perfcl_vreg")):
        orig = body(base, label)
        overlay = body(v2, label, True)
        props = properties(orig)
        props.update(properties(overlay))
        # These algorithms require these exact features and no temperature/
        # core-count/aging hardware measurements in the board profile.
        combined = orig + overlay
        if any(x in combined for x in ("corner-band-allow-", "qcom,cpr-voltage-steps",
                                      "qcom,cpr-open-loop-voltage-min-diff")):
            raise ValueError("new dynamic calibration policy requires implementation")
        for key in ("qcom,allow-voltage-interpolation", "qcom,allow-quotient-interpolation",
                    "qcom,cpr-scaled-open-loop-voltage-as-ceiling"):
            if key not in combined:
                raise ValueError(f"required profile flag missing: {key}")
        if props["qcom,allow-aging-voltage-adjustment"] != [0]:
            raise ValueError("aging measurement is not implemented by this pure decoder")
        counts = props["qcom,cpr-speed-bin-corners"]
        if counts != ([22] * 4 if cluster == 0 else [32, 26, 30, 31]):
            raise ValueError("unexpected sagit corner counts")
        for field, prop in FIELDS.items():
            data = props[prop]
            if field == "counts":
                # Per-combo corner counts must agree with the speed-bin map.
                if len(data) == 1:
                    data *= 32
                if data != [n for n in counts for _ in range(8)]:
                    raise ValueError("CPR rev / speed-bin corner map changed")
            lines.append(f"static constexpr int64_t c{cluster}_{field}[] = {{")
            for start in range(0, len(data), 10):
                lines.append("    " + ", ".join(str(x) for x in data[start : start + 10]) + ",")
            lines.append("};")
        lines.append(f"static constexpr Cluster cluster{cluster} = {{")
        for field in FIELDS:
            lines.append(f"    {{c{cluster}_{field}, sizeof(c{cluster}_{field})/sizeof(int64_t)}},")
        lines.append("};")
    clock = properties(body(v2, "clock_cpu", True))
    lines.append("struct OSMSource { uint32_t hz, frequency, overrideValue, spare, corner; };")
    for cluster in range(2):
        for speed in range(4 if cluster else 1):
            key = f"qcom,{'perfcl' if cluster else 'pwrcl'}-speedbin{speed}-v0"
            data = clock[key]
            if len(data) % 5 or not 1 <= len(data) // 5 <= 40:
                raise ValueError("invalid OSM source table")
            lines.append(f"static constexpr OSMSource osm{cluster}_{speed}[] = {{")
            for i in range(0, len(data), 5):
                hz, freq, override, spare, corner = data[i : i + 5]
                lines.append(f"    {{{hz}, 0x{freq:08x}, 0x{override:08x}, {spare}, {corner - 1}}},")
            lines.append("};")
    lines += ["} }", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != data:
            raise SystemExit("CPRh generated tables differ; regenerate")
    else:
        OUTPUT.write_text(data)
